"""Turn podcast/scripts/epNN.txt into podcast/audio/epNN.mp3 with two Kokoro voices (local, free).

Script format: line 1 "# Episode N: title", then one turn per line, "A: ..." (Alex) or "B: ..." (Sam).
Needs Apple Silicon, ffmpeg, and a venv with: mlx-audio soundfile "misaki[en]"
Usage: python tools/podcast.py [ep01 ep02 ...]   (default: every script without an mp3)
       python tools/podcast.py --index           (only rewrite data/podcast.js)
Afterwards it rewrites data/podcast.js, which the Podcast page reads.
"""
import json, pathlib, re, subprocess, sys
import numpy as np
import soundfile as sf
from mlx_audio.tts.utils import load_model

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCRIPTS, AUDIO = ROOT / "podcast" / "scripts", ROOT / "podcast" / "audio"
VOICES = {"A": "am_michael", "B": "af_heart"}
RATE, PAUSE = 24000, 0.35  # seconds of silence between turns

def render(model, script, out):
    parts, silence = [], np.zeros(int(RATE * PAUSE), dtype=np.float32)
    lines = [l for l in script.read_text().splitlines() if l[:3] in ("A: ", "B: ")]
    for i, line in enumerate(lines, 1):
        print(f"\r  {script.stem}: turn {i}/{len(lines)}", end="", flush=True)
        for r in model.generate(text=line[3:], voice=VOICES[line[0]], speed=1.0, lang_code="a"):
            parts.append(np.array(r.audio, dtype=np.float32))
        parts.append(silence)
    wav = out.with_suffix(".wav")
    sf.write(wav, np.concatenate(parts), RATE)
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(wav), "-ac", "1", "-b:a", "64k", str(out)], check=True)
    wav.unlink()
    print(f"\r  {out.name} done" + " " * 20)

def write_index():
    """data/podcast.js: title, lecture, length and transcript of every episode that has an mp3."""
    eps = []
    for mp3 in sorted(AUDIO.glob("ep*.mp3")):
        lines = (SCRIPTS / f"{mp3.stem}.txt").read_text().splitlines()
        n, title = re.match(r"# Episode (\d+): (.*)", lines[0]).groups()
        secs = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(mp3)],
                                    capture_output=True, text=True, check=True).stdout)
        turns = [[l[0], l[3:]] for l in lines if l[:3] in ("A: ", "B: ")]
        eps.append(dict(id=mp3.stem, n=int(n), title=title, doc=f"c{n}", src=f"podcast/audio/{mp3.name}", secs=round(secs), turns=turns))
    (ROOT / "data" / "podcast.js").write_text(
        "// Generated by tools/podcast.py from podcast/scripts/. A = Alex, B = Sam.\n"
        f"window.TTCS_PODCAST = {json.dumps(eps, ensure_ascii=False, indent=0)};\n")
    print(f"data/podcast.js: {len(eps)} episodes")

def main():
    AUDIO.mkdir(exist_ok=True)
    args = [a for a in sys.argv[1:] if a != "--index"]
    names = args or [s.stem for s in sorted(SCRIPTS.glob("ep*.txt")) if not (AUDIO / f"{s.stem}.mp3").exists()]
    if names and "--index" not in sys.argv:
        model = load_model("prince-canuma/Kokoro-82M")
        for n in names:
            render(model, SCRIPTS / f"{n}.txt", AUDIO / f"{n}.mp3")
    write_index()

if __name__ == "__main__":
    main()
